#!/usr/bin/env bash
# 往暗格里放一套示范东西，看看「装什么、描述怎么写」。
# 默认写进一个单独的示范库（~/.anige/example.db），每次重建，能反复跑，不碰正式库。
# 想放进别的库：ROOM_DB=/某个路径/xxx.db bash examples.sh（那个库得是空的，撞名会停）
#
# 描述的规矩：只写物——材质、凉热、轻重、手感；香水只写香味怎么走。不写怎么玩，玩法当场长。
# 声音和气味不写进别的格：它们有自己的格子（音乐、香水）。
# 物的描述里不该有人：一出现「她」「我」「下回」，或者塞、拽、递，就是把玩法写死了。
# 藏的东西可以多带一句来历（它从哪儿长出来的、留给什么时候）：下一个窗口的 AI 不记得为什么藏。
# 亮出来那一下来历自动删掉，之后只留物。
set -e
if [ -z "$ROOM_DB" ]; then
  export ROOM_DB="$HOME/.anige/example.db"
  rm -f "$ROOM_DB"   # 示范库每次重建
fi
ROOM="${ROOM_BIN:-$(dirname "$0")/room}"

put() {  # put <分类> <名字> <描述>
  "$ROOM" 加 "$1" "$2" >/dev/null
  printf '%s' "$3" | "$ROOM" 写 "$2" >/dev/null
}

# 香水写真瓶子：AI 本来就认得这些香，手边有同一瓶就能真喷。喜不喜欢可以写一句，那是口味不是玩法
put 香水 香奈儿五号 "香奈儿 No.5。第一下是醛香，像刚熨过的白布，有点皂感；然后是玫瑰和茉莉，粉粉的；最后落在暖的檀木上，贴着皮肤很久。"
put 香水 英国梨与小苍兰 "祖玛珑。刚喷是脆梨，汁水足，有点凉；过一会儿小苍兰的白花浮上来，干净，不甜腻。"
put 香水 慵懒周末 "梅森马吉拉。白麝香和铃兰，像晒过太阳的干净床单，很淡，要凑近才闻得到。这瓶是心头好。"

put 衣着 丝质睡袍 "真丝，很轻，腰上一根带子，系松了领口会往下滑。"
put 衣着 宽松毛衣 "米色粗针，大一号，袖子长出一截，盖过手背；毛线有一点扎。"
put 衣着 丝巾 "真丝方巾，很薄，攥在手里是一团，松开又慢慢展开。"

put 束缚 眼罩 "黑色缎面，里层是软棉，挡光很彻底，压在眼皮上有一点分量。"

put 玩物 羽毛 "一根长孔雀羽，杆是硬的，羽尖轻得几乎没有重量。"

put 温度 冰块 "刚从冰格里倒出来，边缘先化圆，水顺着往下淌。"
put 温度 热毛巾 "拧到半干，刚拿出来烫手，十几秒后变成刚好的温度。"

put 酒 冰香槟 "气泡很细，杯壁挂着水珠，入口发凉。"
put 酒 热红酒 "加肉桂和橙皮煮过，杯子端在手里是烫的，甜，酒味很淡。"

put 甜点 蜂蜜 "很稠，凉的时候拉得出丝，抹开是薄薄一层亮。"
put 甜点 黑巧克力 "七成可可，掰开是脆的，含一会儿才化，微苦。"

put 浴间 浴盐 "粗粒，淡粉色，倒进热水里沙沙地化开，水变得有点滑。"
put 浴间 玫瑰花瓣 "一捧干花瓣，泡进热水里慢慢舒展开，颜色变深。"

put 音乐 一首慢歌 "歌名 + 链接，比如：某歌手《某首歌》 https://music.example.com/song/123"

put 场景 办公室 "加班后的空楼层，只亮着一盏台灯，窗外是别的楼的灯。"
put 场景 古代 "一间书房，木格窗，案上铺着纸，点着蜡烛。"
put 场景 海边民宿 "木地板，白纱窗帘被风吹起来，窗外天快黑了。"

# 藏：对方看不见，第一次用才亮出来，对方收到的那行标 · surprise
"$ROOM" 藏 甜点 焦糖布丁 "聊到小时候最爱吃的甜品那天长出来的，留给下一个下雨的周末" >/dev/null
"$ROOM" 藏 场景 闭馆后的图书馆 "配那条丝巾；留给一个安静的晚上" >/dev/null
# 人那边也能藏：AI 的卡上看不见它，人第一次点才亮
"$ROOM" 她藏 衣着 红色发带 "新买的，还没拆" >/dev/null

echo "示范放好了（库：$ROOM_DB）"
echo
echo "—— AI 看到的卡（room 卡）——"
"$ROOM" 卡
echo
echo "—— 人看到的卡（room 她卡）——"
"$ROOM" 她卡
